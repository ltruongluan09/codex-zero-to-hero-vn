create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique not null,
  name text,
  avatar_url text,
  provider text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.subscribers (
  id bigint generated by default as identity primary key,
  email text unique not null,
  user_id uuid references auth.users(id) on delete set null,
  name text,
  avatar_url text,
  source text not null default 'follow_form',
  provider text not null default 'email',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.followed_projects (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  project_slug text not null,
  created_at timestamptz not null default now(),
  unique (user_id, project_slug)
);

create table if not exists public.memberships (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  plan text not null default 'free',
  status text not null default 'active',
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id)
);

create table if not exists public.ai_usage_limits (
  id bigint generated by default as identity primary key,
  bucket_key text not null,
  client_ip text not null,
  action text not null,
  window_start timestamptz not null default date_trunc('day', now()),
  count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (bucket_key, window_start)
);

create or replace function public.consume_ai_usage(
  p_bucket_key text,
  p_client_ip text,
  p_action text,
  p_max integer default 5
)
returns table (
  allowed boolean,
  used integer,
  remaining integer,
  reset_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_window_start timestamptz := date_trunc('day', now());
  v_reset_at timestamptz := date_trunc('day', now()) + interval '1 day';
  v_used integer;
begin
  insert into public.ai_usage_limits (bucket_key, client_ip, action, window_start, count)
  values (p_bucket_key, p_client_ip, p_action, v_window_start, 1)
  on conflict (bucket_key, window_start)
  do update set
    count = public.ai_usage_limits.count + 1,
    updated_at = now()
  where public.ai_usage_limits.count < p_max
  returning count into v_used;

  if v_used is null then
    select count into v_used
    from public.ai_usage_limits
    where bucket_key = p_bucket_key
      and window_start = v_window_start;

    return query select false, coalesce(v_used, p_max), 0, v_reset_at;
    return;
  end if;

  return query select true, v_used, greatest(p_max - v_used, 0), v_reset_at;
end;
$$;

